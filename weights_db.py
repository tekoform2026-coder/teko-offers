def get_item_weight(item_name: str) -> float:
    """
    Връща единичното тегло в kg за даден артикул / код.
    """
    if not item_name:
        return 0.0
    
    clean_name = str(item_name).strip()
    if clean_name in WEIGHTS_DB:
        return WEIGHTS_DB[clean_name]
    
    for key, weight in WEIGHTS_DB.items():
        if key.lower() == clean_name.lower():
            return weight

    for key, weight in WEIGHTS_DB.items():
        if key.lower() in clean_name.lower() or clean_name.lower() in key.lower():
            return weight
            
    return 0.0
